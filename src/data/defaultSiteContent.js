export function toYouTubeEmbedUrl(url) {
  if (!url) return DEFAULT_SITE_CONTENT.home.videoYoutubeUrl;
  const trimmed = url.trim();
  if (trimmed.includes('youtube.com/embed/')) {
    return trimmed;
  }
  const watchMatch = trimmed.match(/[?&]v=([^&#]+)/);
  const shortMatch = trimmed.match(/youtu\.be\/([^?&#]+)/);
  const videoId = (watchMatch && watchMatch[1]) || (shortMatch && shortMatch[1]);
  if (videoId) {
    return `https://www.youtube.com/embed/${videoId}?autoplay=1&mute=1&loop=1&playlist=${videoId}&controls=0&showinfo=0&rel=0&modestbranding=1&playsinline=1&disablekb=1&iv_load_policy=3&cc_load_policy=0&fs=0&start=0`;
  }
  return trimmed;
}
